# Arithmetic operators

a = 34 
b = 4
c = a + b # Addition
print(c)

# Assignment operators
a = 4-2 # Assign 4-2 in a
print(a)
b = 6
b += 3  # Increment the value of b by 3 and then assign it to b
# b -= 3  # Decrement the value of b by 3 and then assign it to b
print(b) 

# Comparison operators

d = 5==5 # Check if 5 is equal to 5
print(d)

e = 5!=3 # Check if 5 is not equal to 3
print(e)

f = 5>3 # Check if 5 is greater than 3
print(f)

g = 5<3 # Check if 5 is less than 3
print(g)

h = 5>=3 # Check if 5 is greater than or equal to 3
print(h)

i = 5<=3 # Check if 5 is less than or equal to 3
print(i)


# Logical operators
e = True and False # Check if both of the two conditions are True

# Truth Table for OR operator
print("True or False is ", True or False)
print("True or True is ", True or True)
print("False or False is ", False or False)
print("False or True is ", False or True)     

# Truth Table for AND operator
print("True and False is ", True and False)
print("True and True is ", True and True)
print("False and False is ", False and False)
print("False and True is ", False and True)

print(not(True)) # Check if True is not True